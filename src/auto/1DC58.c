extern u8 D_800960F0[];
extern u8 D_800961E0[];
extern u8 D_80130640[];
extern u8 D_80096320[];
void Vec3f_Length(f32 *, Vec3f *);
void Init_TriNormals(void);
float sqrtf(float);

void RigidBody_Init(RigidBody *rb, RigidBodyParams *p) {
    Vec3f zero = { 0.0f, 0.0f, 0.0f };
    Vec3f ex = { 1.0f, 0.0f, 0.0f };
    Vec3f ey = { 0.0f, 1.0f, 0.0f };
    Vec3f ez = { 0.0f, 0.0f, 1.0f };
    s32 k;
    f32 a;
    f32 b;
    f32 c;
    f32 x2, y2, z2, m;
    f32 r, I, wm;

    /* all f32, from the car's spec as loaded: converted before being copied into the
       body and wheels, where the physics copies them into locals */
    PORT_CONVERT(p, sizeof(RigidBodyParams) / 4, 4);
    rb->xC = p->x0;
    rb->x10 = 1.0f / p->x0;
    rb->x130 = p->xC;
    Vec3f_Length(&rb->x120, &rb->x130);
    rb->x120 = rb->x120 + 0.1;
    rb->x11C = p->x8;
    rb->x148 = 10;
    rb->x154 = 20;
    rb->x160 = 12;
    rb->x13C = D_800960F0;
    rb->x14C = D_800961E0;
    Init_TriNormals();
    y2 = rb->x130.y * rb->x130.y;
    z2 = rb->x130.z * rb->x130.z;
    m = rb->xC;
    x2 = rb->x130.x * rb->x130.x;
    rb->x14 = m * (y2 + z2) * 0.33333334f;
    rb->x18 = m * (x2 + z2) * 0.33333334f;
    rb->x1C = m * (x2 + y2) * 0.33333334f;
    rb->x20 = 1.0f / rb->x14;
    rb->x24 = 1.0f / rb->x18;
    rb->x28 = 1.0f / rb->x1C;
    rb->x140 = D_80130640;
    rb->x158 = D_80096320;
    rb->x2C = zero;
    rb->x38 = zero;
    rb->x44 = zero;
    rb->x50 = ex;
    rb->x5C = ey;
    rb->x68 = ez;
    rb->x74 = rb->x14;
    rb->x78 = rb->x18;
    rb->x7C = rb->x1C;
    rb->x80 = 0.0f;
    rb->x84 = 0.0f;
    rb->x88 = 0.0f;
    rb->x8C = rb->x20;
    rb->x90 = rb->x24;
    rb->x94 = rb->x28;
    rb->x98 = 0.0f;
    rb->x9C = 0.0f;
    rb->xA0 = 0.0f;
    rb->xA4 = zero;
    rb->xB0 = zero;
    rb->xBC = zero;
    rb->xC8 = ex;
    rb->xD4 = ey;
    rb->xE0 = ez;
    rb->xEC = rb->x14;
    rb->xF0 = rb->x18;
    rb->xF4 = rb->x1C;
    rb->xF8 = 0.0f;
    rb->xFC = 0.0f;
    rb->x100 = 0.0f;
    rb->x104 = rb->x20;
    rb->x108 = rb->x24;
    rb->x10C = rb->x28;
    rb->x110 = 0.0f;
    rb->x114 = 0.0f;
    rb->x118 = 0.0f;
    rb->x868 = 100;
    rb->x164 = 0;
    rb->x86C = 1;
    rb->x870 = 0;
    rb->x874 = 0;
    a = p->x1C * 0.01745;
    b = p->x18 * 0.01745;
    c = (a * 27.777779f) / (b - a);
    rb->x170 = c;
    rb->x174 = b * c;
    p->x38.v[1] = p->x38.v[1] * sqrtf(p->x38.v[0] * p->x0);
    for (k = 0; k < 4; k++) {
        Wheel *w = (Wheel *)((u8 *)rb + k * 0x1BC);
        w->x300 = p->x50[k];
        w->x2E8 = p->x38;
        w->x30C = 0;
        w->x310 = 0;
        w->x314 = 1.0f;
        w->x320 = 0;
        w->x330 = 1.0f;
        w->x184 = 30.0f;
        w->x188 = 1.0f / p->x20;
        w->x298 = p->x24;
        w->x294 = p->x28;
        w->x2A8 = p->x2C;
        r = w->x298;
        wm = w->x184;
        I = wm * (3.0f * r * r + 0.36f) * 0.083333336f;
        w->x18C = I;
        w->x194 = wm * (6.0f * r * r) * 0.2f;
        w->x190 = I;
        w->x198 = 1.0f / w->x18C;
        w->x1A0 = 1.0f / w->x194;
        w->x19C = 1.0f / w->x190;
        w->x2D8 = 0;
        w->x2C0 = 0;
        w->x2D0 = 0;
        w->x2B4 = 0;
        w->x1A4 = p->x80[k];
        w->x1B0 = zero;
        w->x1BC = zero;
        w->x1C8 = ex;
        w->x1D4 = ey;
        w->x1E0 = ez;
        w->x21C = p->x80[k];
        w->x228 = zero;
        w->x234 = zero;
        w->x240 = ex;
        w->x24C = ey;
        w->x258 = ez;
    }
}
