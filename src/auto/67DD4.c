#include "common.h"
#include "m2c.h"

f32 Math_Exp2f(f32 x) {
    f32 x2;
    f32 x4;

    if (x == 0.0f) {
        return 1.0f;
    }
    if (x > 0.0f) {
        x2 = x * x;
        return 1.0 + x * 0.693147180559944953 + x2 * 0.240226506959100999 + (x2 * x) * 0.055504108664821597
            + (x2 * x2) * 0.00961812910762848035 + (x2 * x2 * x) * 0.00133335581464283999 + (x2 * x2 * x2) * 0.000154035303933816006;
    }
    x = -x;
    x2 = x * x;
    x4 = x2 * x2;
    return 1.0 / (1.0 + x * 0.693147180559944953 + x2 * 0.240226506959100999 + (x2 * x) * 0.055504108664821597
        + x4 * 0.00961812910762848035 + (x4 * x) * 0.00133335581464283999 + (x4 * x2) * 0.000154035303933816006);
}
