#!/usr/bin/env python3
"""List the source files the PC port leaves out because port/src replaces them.

The port keeps the audio library, gu, the libm functions, the SDK scheduler and
audio manager, and replaces the rest of libultra (threads, message queues,
timers, VI, PI, AI, SP, DP, SI, controllers, Controller Pak, rumble, caches)
plus the libc string functions the host provides. A file is left out when every
function in it is replaced; a file mixing kept and replaced functions is an
error, so it gets split or handled by hand.

Reads docs/functions.md; writes port/sdk_excluded.cmake.
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

KEEP_OS = {'osCreateScheduler', 'osScAddClient', 'osScRemoveClient', 'osScGetCmdQ'}
REPLACED_OTHER = {
    # libc the host provides
    'bzero', 'bcopy', 'bcmp', 'memcpy', 'memset', 'memcmp', 'strlen', 'strcpy', 'strchr',
    'strcat', 'strcmp', 'strncat', 'strrchr', 'sprintf', 'proutSprintf', '_Printf',
    'sqrt', 'sqrtf',
    # libgcc helpers
    '__cmpdi2', '__muldi3', '__divdi3', '__udivdi3', '__umoddi3', '__fixunsdfdi', '__floatdidf',
    '__floatdisf',
    # Controller Pak internals named by their strings
    'corrupted', 'corrupted_init',
    # PI domain setup, a Controller Pak helper, the VI manager thread
    'func_8006DCF0', 'func_8006FAA0', 'viMgrMain',
}


# Mixed files whose replaced functions are behind #ifndef TARGET_PC in the source
MIXED_HANDLED = {'src/auto/54900.c'}


def replaced(name):
    if name in KEEP_OS:
        return False
    if name.startswith(('os', '__os', '_os')):
        return True
    return name in REPLACED_OTHER


def main():
    root = Path(__file__).resolve().parents[2]
    files = defaultdict(list)
    for line in (root / 'docs/functions.md').read_text().splitlines():
        m = re.match(r'\| `8\w+` \| `\w+` \| \w+ \| `(\w+)` \| `([^`]+)`', line)
        if m and m.group(2).endswith('.c'):
            files[m.group(2)].append(m.group(1))
    out, bad = [], []
    for f, names in sorted(files.items()):
        r = [replaced(n) for n in names]
        if all(r):
            out.append(f)
        elif any(r) and f not in MIXED_HANDLED:
            bad.append(f'{f}: {" ".join(names)}')
    for b in bad:
        print('mixed file:', b, file=sys.stderr)
    text = ['# Generated by tools/port/sdk_files.py: SDK files port/src replaces.',
            'set(PORT_SDK_EXCLUDED']
    text += [f'    {f}' for f in out]
    text.append(')')
    (root / 'port/sdk_excluded.cmake').write_text('\n'.join(text) + '\n')
    print(f'{len(out)} files left out', file=sys.stderr)
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
