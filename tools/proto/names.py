#!/usr/bin/env python3
"""Generate include/ids.h from the debug menu name pool in the prototype ROM.

Usage: python3 tools/proto/names.py baserom_proto.z64 > include/ids.h
"""
import hashlib
import struct
import sys

PROTO_SHA1 = "6c20de318bd6c96409858be3c09e14ce01b829a9"
BASE = 0x80000400 - 0x1000
POOL = 0x800B4BC4  # array of char pointers used by the debug menu's list items

# (enum name, prefix comment, first pool index, count). Ranges come from the
# menu items that use them; see docs/prototype.md.
GROUPS = [
    ("SfxId", "Sound effects ('SFX Name' item).", 15, 38),
    ("VoiceId", "Announcer and voice samples ('VOICE Name' item).", 53, 145),
    ("SpriteId", "Sprites and text strings share one ID space ('Sprite ID' item, 0 to 526).", 222, 527),
    ("DamageSpriteId", "Car damage indicator sprites ('Damage Sprites' > 'Sprite ID').", 749, 16),
]

LISTS = [
    ("Difficulty", "World Tour difficulty ('World Tour' item).", 198, 4, ["Novice", "Amateur", "Professional", "Legend"]),
    ("AiTargetBias", "How an AI car picks its target ('A Base Tenac' item).", 214, 8, None),
]


def main():
    rom = open(sys.argv[1], "rb").read()
    if hashlib.sha1(rom).hexdigest() != PROTO_SHA1:
        sys.exit("not the expected prototype ROM (big-endian .z64)")

    def name(i):
        p = struct.unpack(">I", rom[POOL - BASE + 4 * i:POOL - BASE + 4 * i + 4])[0] - BASE
        return rom[p:rom.index(b"\0", p)].decode("ascii").strip()

    out = [
        "#ifndef IDS_H",
        "#define IDS_H",
        "",
        "/*",
        " * Generated by tools/proto/names.py from the prototype's debug menu.",
        " * The values are the prototype's. The sprite and text IDs that retail passes to",
        " * Ui_AddElement match, for example OPT_LINE1_STR to OPT_LINE8_STR on the options",
        " * screen and the Controller Pak warning sprites.",
        " */",
    ]
    for enum, doc, first, count in GROUPS:
        out += ["", f"/* {doc} */", f"typedef enum {enum} {{"]
        names = []
        for k in range(count):
            n = name(first + k)
            # A missing comma in the original source joined these two literals,
            # so every later sound name in the menu is off by one.
            if n == "FX_TRAV_DIRT_SNOW1FX_HIT_SIDE_SIDE1":
                names += ["FX_TRAV_DIRT_SNOW1", "FX_HIT_SIDE_SIDE1"]
            else:
                names.append(n)
        seen = set()
        for k, n in enumerate(names):
            n = n.replace(" ", "_").upper()
            if enum == "DamageSpriteId":
                n = "DAMAGE_SPRITE_" + n.removesuffix("_SP")
            if n in seen or not n.isidentifier():
                n = f"{enum.upper()}_{k}"
            seen.add(n)
            out.append(f"    /* {k:3d} */ {n},")
        out += [f"}} {enum};"]
    for enum, doc, first, count, override in LISTS:
        out += ["", f"/* {doc} */", f"typedef enum {enum} {{"]
        for k in range(count):
            n = override[k] if override else name(first + k)
            n = n.replace(" ", "_").upper()
            prefix = "DIFFICULTY_" if enum == "Difficulty" else "AI_TARGET_"
            if n.startswith(prefix):
                prefix = ""
            out.append(f"    /* {k} */ {prefix}{n},")
        out += [f"}} {enum};"]
    out += ["", "#endif", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
